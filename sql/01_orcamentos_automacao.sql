-- Orçamentos de Automação — tabelas, permissões e bucket de fotos
-- Rodar uma vez no SQL Editor do Supabase (projeto mqdhavyaeujufhlqdlfg).
-- Só cria coisas novas: não altera nenhuma tabela existente.

create table if not exists public.automacao_produtos (
  id uuid primary key default gen_random_uuid(),
  codigo text unique not null,          -- código do Conta Azul
  nome text not null,                   -- nome técnico (ERP)
  nome_comercial text,                  -- nome que aparece pro cliente
  descricao text,                       -- linha curta do que o produto faz
  preco numeric(12,2) not null default 0,
  observacao text,
  foto_url text,
  foto_path text,
  ativo boolean not null default true,  -- aparece na busca do orçamento
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.automacao_orcamentos (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity (start with 1) unique,
  lead_id bigint references public.leads(id) on delete set null,
  seller_id uuid references public.sellers(id) on delete set null,
  cliente_nome text not null,
  cliente_telefone text,
  cliente_endereco text,
  validade date,
  itens jsonb not null default '[]'::jsonb,  -- [{ambiente, produto_id, codigo, nome, descricao, foto_url, qtd, preco}]
  desconto numeric(12,2) not null default 0,
  condicoes text,
  status text not null default 'rascunho',   -- rascunho | enviado | aprovado | perdido
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists automacao_orcamentos_lead_idx on public.automacao_orcamentos(lead_id);

-- Só quem está logado no CRM (Supabase Auth) lê e grava
alter table public.automacao_produtos enable row level security;
alter table public.automacao_orcamentos enable row level security;

drop policy if exists automacao_produtos_interno on public.automacao_produtos;
create policy automacao_produtos_interno on public.automacao_produtos
  for all to authenticated using (true) with check (true);

drop policy if exists automacao_orcamentos_interno on public.automacao_orcamentos;
create policy automacao_orcamentos_interno on public.automacao_orcamentos
  for all to authenticated using (true) with check (true);

-- Bucket das fotos: leitura pública (pra aparecer no PDF), escrita só logado
insert into storage.buckets (id, name, public)
values ('automacao-produtos', 'automacao-produtos', true)
on conflict (id) do nothing;

drop policy if exists automacao_fotos_leitura on storage.objects;
create policy automacao_fotos_leitura on storage.objects
  for select to public using (bucket_id = 'automacao-produtos');
drop policy if exists automacao_fotos_insert on storage.objects;
create policy automacao_fotos_insert on storage.objects
  for insert to authenticated with check (bucket_id = 'automacao-produtos');
drop policy if exists automacao_fotos_update on storage.objects;
create policy automacao_fotos_update on storage.objects
  for update to authenticated using (bucket_id = 'automacao-produtos');
drop policy if exists automacao_fotos_delete on storage.objects;
create policy automacao_fotos_delete on storage.objects
  for delete to authenticated using (bucket_id = 'automacao-produtos');
